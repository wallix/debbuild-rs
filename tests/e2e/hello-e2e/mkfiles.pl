#!/usr/bin/perl
# mkfiles.pl DIR: files carrying the time of the build, for dh_strip_nondeterminism to
# normalize: a jar and a zip archive, a PNG image, a message catalog, a javadoc page and a
# Python zip application. Only Perl's core modules.
use strict;
use warnings;
use Compress::Zlib qw(compress crc32);

my $dir = shift or die "usage: mkfiles.pl DIR\n";
my $now = time;
my @t = gmtime $now;

sub put {
    my ($name, $data, $mode) = @_;
    open my $f, '>:raw', "$dir/$name" or die "$dir/$name: $!";
    print $f $data;
    close $f or die "$dir/$name: $!";
    chmod $mode // 0644, "$dir/$name";
}

sub deflate { my $z = compress(shift, 9); return substr($z, 2, -4); }

# A zip archive of [name, data, deflate?], with the build time in each member.
sub zip {
    my ($out, $cd) = ('', '');
    my $dos_time = ($t[2] << 11) | ($t[1] << 5) | ($t[0] >> 1);
    my $dos_date = (($t[5] - 80) << 9) | (($t[4] + 1) << 5) | $t[3];
    for my $m (@_) {
        my ($name, $data, $deflate) = @$m;
        my $body = $deflate ? deflate($data) : $data;
        my $extra = pack('vvCV', 0x5455, 5, 1, $now) . pack('vvCCVCV', 0x7875, 11, 1, 4, $<, 4, (split ' ', $()[0]);
        my @fields = (20, 0, $deflate ? 8 : 0, $dos_time, $dos_date, crc32($data), length $body, length $data);
        my $offset = length $out;
        $out .= pack('VvvvvvVVVvv', 0x04034b50, @fields, length $name, length $extra) . $name . $extra . $body;
        my $mode = $name =~ m{/$} ? 040755 : 0100644;
        $cd .= pack('VvvvvvvVVVvvvvvVV', 0x02014b50, 0x031e, @fields, length $name, length $extra, 0, 0, 0,
            $mode << 16, $offset) . $name . $extra;
    }
    my $n = @_;
    return $out . $cd . pack('VvvvvVVv', 0x06054b50, 0, 0, $n, $n, length $cd, length $out, 0);
}

my $greeting = "hello from debbuild-rs\n" x 20;
my @members = (
    ['META-INF/', ''],
    ['META-INF/MANIFEST.MF', "Manifest-Version: 1.0\r\nBnd-LastModified: ${now}000\r\n\r\n"],
    ['greeting.txt', $greeting, 1],
    ['doc/index.html', "<!-- Generated by javadoc (17) on " . gmtime($now) . " -->\n<html></html>\n"],
);
put('hello-e2e.jar', zip(@members));
# the zip handler leaves the content of members alone
put('hello-e2e.zip', zip(['doc/', ''], ['greeting.txt', $greeting, 1], ['doc/README', "hello\n"]));
put('hello-e2e-app', "#!/usr/bin/python3\n" . zip(['__main__.py', "print('hello from debbuild-rs')\n"]), 0755);

sub chunk { my ($type, $data) = @_; return pack('N', length $data) . $type . $data . pack('N', crc32($type . $data)); }
my $date = sprintf('%04d-%02d-%02dT%02d:%02d:%02d+00:00', $t[5] + 1900, $t[4] + 1, @t[3, 2, 1, 0]);
put('hello-e2e.png', "\x89PNG\r\n\x1a\n" . chunk('IHDR', pack('NNCCCCC', 1, 1, 8, 0, 0, 0, 0))
    . chunk('tIME', pack('nCCCCC', $t[5] + 1900, $t[4] + 1, @t[3, 2, 1, 0]))
    . chunk('tEXt', "date:create\0$date") . chunk('IDAT', compress("\0\0")) . chunk('IEND', ''));

my $header = sprintf("Project-Id-Version: hello-e2e\nPOT-Creation-Date: %04d-%02d-%02d %02d:%02d+0000\n"
    . "Content-Type: text/plain; charset=UTF-8\n", $t[5] + 1900, $t[4] + 1, @t[3, 2, 1]);
my ($id, $str) = ('hello from debbuild-rs', 'bonjour de debbuild-rs');
my $strings = 28 + 2 * 16;
my $mo = pack('V7', 0x950412de, 0, 2, 28, 44, 0, $strings)
    . pack('V4', 0, $strings, length $id, $strings + 1)
    . pack('V4', length $header, $strings + length($id) + 2, length $str, $strings + length($id) + length($header) + 3)
    . "\0$id\0$header\0$str\0";
put('hello-e2e.mo', $mo);

put('api.html', "<!DOCTYPE HTML>\n<!-- Generated by javadoc (17) on " . gmtime($now) . " -->\n<html>\n<head>\n"
    . sprintf('<meta name="dc.created" content="%04d-%02d-%02d">', $t[5] + 1900, $t[4] + 1, $t[3]) . "\n</head>\n</html>\n");
